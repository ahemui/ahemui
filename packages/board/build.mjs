// Bundles the board page script and embeds it into the CLI as a string, so `snap serve` can serve the board and
// `snap export` can write a self-contained .snap/backlog.html without shipping extra files.
import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

const out = await build({
  entryPoints: ["src/client.ts"],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  write: false,
  logLevel: "warning",
});
const js = out.outputFiles[0].text;
await writeFile(
  "../cli/src/board-assets.generated.ts",
  `// Generated by packages/board/build.mjs. Do not edit.\nexport const BOARD_JS = ${JSON.stringify(js)};\n`,
);
console.log(`board built (${(js.length / 1024).toFixed(0)} KB) → packages/cli/src/board-assets.generated.ts`);
